/**
 * returnsCompare.ts —— 「总本金 / 总市值」的环比（第三批 #6）
 *
 * ── 为什么不是「累计收益加环比」──
 * 需求原文是「累计收益加环比」。把它按口径展开就会发现它**恒等于刚被删掉的「本期收益」**：
 *
 *   累计收益(本期) − 累计收益(上期)
 *     = (市值ₜ − 本金ₜ) − (市值ₜ₋₁ − 本金ₜ₋₁)
 *     = (市值ₜ − 市值ₜ₋₁) − (本金ₜ − 本金ₜ₋₁)
 *     = 市值变动 − 本期净投入            ← 这正是「本期收益」的定义
 *
 * 上一批刚按「理财侧一律不再出现本期收益」把它从四个页面删干净，这里再算一遍等于换个
 * 标题把它请回来。所以按裁决把环比落在**总本金**与**总市值**两张卡上：它们是收益面板里
 * 唯二「两期相减仍然有意义」的量（本金之差 = 净投入，市值之差 = 净投入 + 涨跌）。
 *
 * ── 不给百分比 ──
 * 市值环比给个百分数会读成「我的持仓涨了 X%」，而它其实混着净投入 —— 与「本期收益」
 * 是同一类误读。卡片上的 `.d` 一行只放金额差，把「差额是什么」交给 `returnsCompareHint()`
 * 的那句话讲清楚。本金/市值两张卡口径一致，不会出现「一张有率、一张没有」。
 *
 * ── 「前一期」的口径 ──
 * 与页面其它环比一致：**同日折叠序列里的前一张**（`dailySeries` + `previousInDaily`）。
 * 不为收益另立一套「上一次盘点」的定义 —— 同一页上两个环比用两套口径，是那种平时
 * 看不出来、但一定会在某天算错的问题。三个页面（首页理财摘要 / 快照详情收益面板 /
 * 报表理财 tab）都调用这里，口径只有一份。
 */
import type { Micro, ReturnsPanelDTO } from '@app/shared';

export interface ReturnsCompare {
  /** 本金净投入 = 本期本金 − 上期本金 */
  principal: Micro;
  /** 市值变动 = 本期市值 − 上期市值（含净投入与涨跌） */
  market: Micro;
}

/**
 * 两期的收益面板相减。任一侧缺失（没有前一期，或那一期的面板还没取回来）时返回 `null`，
 * 由调用方按 `<PrevCompare>` 的三态渲染。
 *
 * 直接相减不做任何符号修正：本金减少（赎回）本来就该显示为负数。
 */
export function returnsCompare(
  cur: ReturnsPanelDTO | null | undefined,
  prev: ReturnsPanelDTO | null | undefined
): ReturnsCompare | null {
  if (!cur || !prev) return null;
  return {
    principal: cur.principal - prev.principal,
    market: cur.market - prev.market
  };
}

/**
 * 三个页面共用的口径小字。
 *
 * 两期面板覆盖的**账户集合可能不同**（中途开启/关闭本金跟踪、账户归档…），
 * 那时相减得到的是「集合变化 + 金额变化」的混合物。这不是缺陷 —— 是本位币口径下
 * 唯一能算的环比 —— 但必须写出来，否则用户会拿它当「我的钱变了多少」。
 *
 * `count` 是本期面板纳入统计的账户数，与快照详情页原来挂在「总本金」卡上的那句
 * 「N 个账户纳入统计」是同一个数：那句话被挪到这一行，是为了让两张卡的 `.d` 都留给环比。
 */
export function returnsCompareHint(count: number): string {
  return (
    `环比 = 与前一期的同一面板相比（本位币口径）· 本面板纳入 ${count} 个账户；` +
    '两期覆盖的账户可能不同，市值差额同时包含净投入与涨跌。'
  );
}
